"""
Orchestrator of the scalability curves on the SQLite side: for each
sub-dataset generated by make_subsets.py, it measures in sequence:
  1. ingestion time (loader/load_sqlite.py::load, timed here,
     not re-read from logs: a fresh and reproducible measurement);
  2. size of the resulting .sqlite file;
  3. execution time of the 8 queries (benchmark/bench_queries.py).

It saves everything in a single CSV (one row per size+metric) in
benchmark/results/scaling_sqlite.csv, so that the scalability charts can be
built without having to re-run the measurements.

The clustering IS executed per size and its own cost recorded as
cluster_s. On SQLite it is label propagation, which may not converge at
the larger sizes: that failure is caught and recorded, because it is
itself the reported result for Q7.
address_clusters on the DBs generated by this script.
"""
import csv
import glob
import os
import sqlite3
import statistics
import sys
import time

sys.path.insert(0, ".")
sys.path.insert(0, "loader")      # load_sqlite.py does "from common import ...", it assumes this path
sys.path.insert(0, "clustering")  # cluster_sqlite.py is imported the same way
from load_sqlite import load as load_sqlite
from load_prices import load_sqlite as load_prices_sqlite
from cluster_sqlite import run as cluster_sqlite
from benchmark.bench_queries import bench_sqlite


def find_subsets(subsets_dir: str) -> list[tuple[int, str]]:
    """Returns [(n_blocks, path), ...] sorted by increasing size,
    reading the number of blocks from the file name subset_NNNNN.jsonl."""
    paths = sorted(glob.glob(os.path.join(subsets_dir, "subset_*.jsonl")))
    result = []
    for p in paths:
        name = os.path.basename(p)
        n = int(name.replace("subset_", "").replace(".jsonl", ""))
        result.append((n, p))
    return result


def wipe_sqlite(db_path: str) -> None:
    """Deletes the database file and its WAL companions.

    This is the whole "from scratch" on the relational side: a file goes
    away. The Neo4j counterpart has to stop the container and delete the
    store from the filesystem (see run_scaling_neo4j.wipe_neo4j), which
    is the reason the two orchestrators are separate scripts.
    """
    for p in (db_path, db_path + "-wal", db_path + "-shm"):
        if os.path.exists(p):
            os.remove(p)


def run_one_size(n_blocks: int, jsonl_path: str, prices_path: str, db_path: str,
                 repeats: int, with_clustering: bool, query_runs: int,
                 query_timeout: float) -> list[dict]:
    rows = []

    # --- ingestion, repeated: every repetition starts from an empty file ---
    times = []
    for i in range(1, repeats + 1):
        wipe_sqlite(db_path)
        print(f"[{n_blocks} blocks] loading ({i}/{repeats})...", file=sys.stderr)
        t0 = time.perf_counter()
        load_sqlite(jsonl_path, db_path, chunk_size=500)
        elapsed = time.perf_counter() - t0
        times.append(elapsed)
        print(f"[{n_blocks} blocks] ingestion {i}/{repeats}: {elapsed:.1f}s", file=sys.stderr)

    ingest_s = statistics.median(times)
    rows.append({"n_blocks": n_blocks, "metric": "ingest_s", "query": "", "value": ingest_s})
    if repeats > 1:
        rows.append({"n_blocks": n_blocks, "metric": "ingest_min_s", "query": "",
                     "value": min(times)})
        rows.append({"n_blocks": n_blocks, "metric": "ingest_stdev_s", "query": "",
                     "value": statistics.stdev(times)})
        print(f"[{n_blocks} blocks] ingestion median: {ingest_s:.1f}s "
              f"(min {min(times):.1f}s, stdev {statistics.stdev(times):.1f}s)",
              file=sys.stderr)

    size_bytes = os.path.getsize(db_path)
    print(f"[{n_blocks} blocks] file size: {size_bytes/1e6:.1f} MB", file=sys.stderr)
    rows.append({"n_blocks": n_blocks, "metric": "disk_bytes", "query": "", "value": size_bytes})

    # Row count to give context to the curves (not just "n blocks")
    conn = sqlite3.connect(db_path)
    n_tx = conn.execute("SELECT COUNT(*) FROM transactions").fetchone()[0]
    conn.close()
    rows.append({"n_blocks": n_blocks, "metric": "n_transactions", "query": "", "value": n_tx})

    # Prices: Q8 joins the transactions with price_history by time
    # interval. Without them that query matches nothing and its timing
    # measures an empty result (measured: 0.094 s instead of 0.523 s on
    # 50 blocks, i.e. the cost of returning nothing).
    # 121 rows, loaded after the timer above so they never enter ingest_s.
    print(f"[{n_blocks} blocks] loading prices (for Q8)...", file=sys.stderr)
    load_prices_sqlite(prices_path, db_path)

    # Clustering: Q7 groups addresses by cluster_id, which only exists
    # after this step. Timed and recorded as its own metric: on 50
    # blocks it costs 194 s against 12 s of loading, because it works on
    # 7.1 million co-ownership edges and not on the blocks.
    # On SQLite this is label propagation and it may NOT converge at the
    # larger sizes: that failure is itself the reported result for Q7,
    # so it is caught and recorded instead of aborting the whole run.
    if with_clustering:
        print(f"[{n_blocks} blocks] clustering (for Q7)...", file=sys.stderr)
        t0 = time.perf_counter()
        try:
            cluster_sqlite(db_path)
            cluster_s = time.perf_counter() - t0
            print(f"[{n_blocks} blocks] clustering: {cluster_s:.1f}s", file=sys.stderr)
            rows.append({"n_blocks": n_blocks, "metric": "cluster_s", "query": "", "value": cluster_s})
            clustered = True
        except Exception as exc:
            cluster_s = time.perf_counter() - t0
            print(f"[{n_blocks} blocks] clustering FAILED after {cluster_s:.1f}s: {exc}",
                  file=sys.stderr)
            rows.append({"n_blocks": n_blocks, "metric": "cluster_error", "query": "",
                         "value": str(exc)})
            clustered = False
    else:
        clustered = False

    print(f"[{n_blocks} blocks] query benchmark...", file=sys.stderr)
    query_results = bench_sqlite(db_path, runs=query_runs, has_clustering=clustered,
                                 per_query_timeout=query_timeout)
    for q, r in query_results.items():
        if "median_s" in r:
            rows.append({"n_blocks": n_blocks, "metric": "query_median_s", "query": q, "value": r["median_s"]})
        elif "timeout_s" in r:
            rows.append({"n_blocks": n_blocks, "metric": "query_timeout", "query": q, "value": r["timeout_s"]})
        elif "error" in r:
            rows.append({"n_blocks": n_blocks, "metric": "query_error", "query": q, "value": r["error"]})

    return rows


if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser(description="SQLite scalability curves (ingestion+disk+queries)")
    parser.add_argument("--subsets-dir", default="benchmark/subsets")
    parser.add_argument("--db-path", default="benchmark/scratch_scaling.sqlite",
                        help="Working DB, rebuilt from scratch for every size")
    parser.add_argument("--out-csv", default="benchmark/results/scaling_sqlite.csv")
    parser.add_argument("--repeats", type=int, default=1,
                        help="Ingestion repetitions per size. 1 gives the curve, "
                             "3 also gives median and stdev")
    parser.add_argument("--prices", default="prices_may.jsonl",
                        help="Price history, needed by Q8")
    parser.add_argument("--cluster-sizes", default="",
                        help="Sizes on which to actually run the clustering, "
                             "e.g. 50,200. Empty means every size; 'none' means "
                             "no size. Q7 is measured only where the clustering "
                             "ran: elsewhere it is reported as skipped, never "
                             "estimated.")
    parser.add_argument("--query-runs", type=int, default=3)
    parser.add_argument("--query-timeout", type=float, default=120.0)
    parser.add_argument("--sizes", default="",
                        help="Comma-separated list of sizes to run (e.g. 50,200). "
                             "Empty means every subset found.")
    args = parser.parse_args()

    subsets = find_subsets(args.subsets_dir)
    if args.sizes:
        wanted = {int(x) for x in args.sizes.split(",")}
        subsets = [(n, p) for n, p in subsets if n in wanted]
    if not subsets:
        print(f"No sub-dataset found in {args.subsets_dir} (run make_subsets.py first)", file=sys.stderr)
        sys.exit(1)

    if args.cluster_sizes.strip().lower() == "none":
        cluster_on = set()
    elif args.cluster_sizes.strip():
        cluster_on = {int(x) for x in args.cluster_sizes.split(",")}
    else:
        cluster_on = {n for n, _ in subsets}

    print(f"Sizes to process: {[n for n, _ in subsets]}", file=sys.stderr)
    print(f"Clustering on: {sorted(cluster_on) if cluster_on else 'no size'}",
          file=sys.stderr)

    # INCREMENTAL writing: the CSV is updated after every size, not
    # only at the end. On long runs (hours) an interruption: a closed session,
    # the machine switched off: would otherwise lose all the measurements already taken.
    os.makedirs(os.path.dirname(args.out_csv), exist_ok=True)
    fieldnames = ["n_blocks", "metric", "query", "value"]
    with open(args.out_csv, "w", newline="") as f:
        csv.DictWriter(f, fieldnames=fieldnames).writeheader()

    total_rows = 0
    for n_blocks, jsonl_path in subsets:
        rows = run_one_size(n_blocks, jsonl_path, args.prices, args.db_path,
                            args.repeats, n_blocks in cluster_on,
                            args.query_runs, args.query_timeout)
        with open(args.out_csv, "a", newline="") as f:
            csv.DictWriter(f, fieldnames=fieldnames).writerows(rows)
        total_rows += len(rows)
        print(f"[{n_blocks} blocks] saved {len(rows)} rows in {args.out_csv}", file=sys.stderr)

    print(f"\nCompleted: {args.out_csv} ({total_rows} rows)", file=sys.stderr)

    wipe_sqlite(args.db_path)
